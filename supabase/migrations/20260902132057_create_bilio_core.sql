CREATE POLICY "room_members_insert_authenticated" ON public.room_members FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());
DROP POLICY IF EXISTS "room_members_update_own" ON public.room_members;
CREATE POLICY "room_members_update_own" ON public.room_members FOR UPDATE TO authenticated USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
DROP POLICY IF EXISTS "room_members_delete_own" ON public.room_members;
CREATE POLICY "room_members_delete_own" ON public.room_members FOR DELETE TO authenticated USING (user_id = auth.uid());

DROP POLICY IF EXISTS "lobby_messages_select_authenticated" ON public.lobby_messages;
