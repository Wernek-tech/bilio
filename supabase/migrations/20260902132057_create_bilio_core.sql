/*
# Bilio core multiplayer foundation

1. New Tables
- `profiles`: persistent player identity, balances, level, XP, and profile text.
- `rooms`: real game rooms with owner, game type, code, status, and capacity.
- `room_members`: room membership, bot flag, and ready state.
- `lobby_messages`: persistent public lobby chat messages.

2. Security
- RLS is enabled on every table.
- Authenticated users may manage only their profile, their room memberships, and rooms they own.
- Public lobby messages are readable to authenticated users and writable only as the sender.
- Room membership reads are limited to rooms the user belongs to.

3. Important notes
- New accounts receive starter balances through the profile insert trigger.
- Room codes are unique and are generated by the application before insert.
*/

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username text NOT NULL UNIQUE,
  about text NOT NULL DEFAULT '',
  avatar_url text,
  level integer NOT NULL DEFAULT 1 CHECK (level >= 1),
  xp integer NOT NULL DEFAULT 0 CHECK (xp >= 0),
  gold integer NOT NULL DEFAULT 5000 CHECK (gold >= 0),
  diamonds integer NOT NULL DEFAULT 1000 CHECK (diamonds >= 0),
  likes integer NOT NULL DEFAULT 0 CHECK (likes >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rooms (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE CASCADE,
  game_type text NOT NULL,
  code text NOT NULL UNIQUE,
  capacity integer NOT NULL DEFAULT 8 CHECK (capacity BETWEEN 2 AND 12),
  status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'playing', 'finished')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.room_members (
  room_id uuid NOT NULL REFERENCES public.rooms(id) ON DELETE CASCADE,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE CASCADE,
  is_bot boolean NOT NULL DEFAULT false,
  ready boolean NOT NULL DEFAULT false,
  joined_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (room_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.lobby_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sender_id uuid NOT NULL DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 400),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.room_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lobby_messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "profiles_select_authenticated" ON public.profiles;
